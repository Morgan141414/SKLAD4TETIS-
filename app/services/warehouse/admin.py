            rows = conn.execute(
                f"SELECT id FROM procedure_consumption_templates {where}"
                f" ORDER BY mis_clinic_id, service_code",
                params,
            ).fetchall()
            return [self._get_procedure_consumption_template(conn, row["id"]) for row in rows]

